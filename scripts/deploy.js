import { account, view, NEAR } from "../lib/near.js";
import fs from "fs";
const S = fs.readFileSync(".keys/suffix", "utf8").trim();
const C = `clearpool-${S}.testnet`, ASP = `cp-asp-${S}.testnet`;
const acc = account(C);
const code = fs.readFileSync("build/clearpool.wasm");
const r = await acc.deployContract(new Uint8Array(code));
console.log("deploy:", r.final_execution_status ?? JSON.stringify(r.status).slice(0, 80));
await acc.callFunction({ contractId: C, methodName: "new", args: { denomination: NEAR(1).toString(), asp_admin: ASP, vk_json: fs.readFileSync("build/vk.json", "utf8") }, gas: 300n * 10n ** 12n });
console.log(await view(C, "get_stats"));
